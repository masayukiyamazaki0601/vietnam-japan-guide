# Apply to all files
def clean_and_deepen(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        html = f.read()
    
    slug = os.path.basename(filepath).replace('.html', '')
    
    # Find the position of first duplicate generic section (s51 or first section after FAQ)
    cta_marker = '<div class="cta-section"'
    cta_pos = html.find(cta_marker)
    
    if slug in DEEP_CONTENT:
        deep_sections = DEEP_CONTENT[slug]
        # Build new sections HTML
        new_sections_html = ''
        for i, (title, content) in enumerate(deep_sections, 1):
            sid = 50 + i
            new_sections_html += f'      <h2 id="s{sid}">{title}</h2>\n{content}\n'
        
        # Insert before CTA
        if cta_pos >= 0:
            # Remove everything between last original section (s5?) and CTA
            # First, find where the original content ends
            original_end = html.find('      <div class="cta-section"')
            if original_end >= 0:
                # Find the start of padding (s51 or next h2 after FAQ)
                # Find last content h2 (the original FAQ or last real section)
                # Let's find all h2 id="sN" positions
                h2_positions = [(m.start(), m.group()) for m in re.finditer(r'<h2 id="s(\d+)">', html)]
                last_original_h2 = None
                for pos, match in h2_positions:
                    num = int(re.search(r's(\d+)', match).group(1))
                    if num <= 10:  # Original sections are s1-s5 typically
                        last_original_h2 = (pos, match)
                
                if last_original_h2:
                    # Find the end of the last original section (next h2 or CTA)
                    last_pos = last_original_h2[0]
                    # Find all content after the last FAQ section's end
                    # Find </h2> after last Q&A
                    faq_end = html.find('</p>', html.rfind('<h3>Q', 0, original_end))
                    if faq_end >= 0:
                        cut_start = faq_end + 4
                        # Remove everything between original FAQ end and CTA
                        new_html = html[:cut_start] + '\n' + new_sections_html + '\n' + html[original_end:]
                    else:
                        new_html = html
                else:
                    new_html = html
            else:
                new_html = html
        else:
            new_html = html
    else:
        new_html = html
    
    # Calculate final lines
    lines = new_html.split('\n')
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_html)
    
    slug_out = os.path.basename(filepath).replace('.html','')
    print(f'  DONE {slug_out}: {len(lines)}行 (unique sections: {len(DEEP_CONTENT.get(slug, []))})')

